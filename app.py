def split_message(text, limit=4000):
    """Split a long Telegram message into safe chunks."""
    chunks = []

    while len(text) > limit:
        split_at = text.rfind("\n", 0, limit)

        if split_at <= 0:
            split_at = limit

        chunks.append(text[:split_at])
        text = text[split_at:].lstrip()

    if text:
        chunks.append(text)

    return chunks


async def send_telegram_async(chat_id, text):
    token = st.secrets["TELEGRAM_BOT_TOKEN"]

    async with Bot(token=token) as bot:
        for chunk in split_message(text):
            await bot.send_message(
                chat_id=chat_id,
                text=chunk,
            )


def send_telegram(chat_id, text):
    asyncio.run(
        send_telegram_async(
            chat_id,
            text,
        )
    )


def build_telegram_report(result):
    score = result.get("match_score", 0)
    level = result.get("match_level", "Unknown")
    explanation = result.get("match_explanation", "")

    strengths = result.get("strengths", [])
    skill_gaps = result.get("skill_gaps", [])
    missing_keywords = result.get("missing_keywords", [])
    projects = result.get("project_analysis", [])
    technical = result.get("technical_preparation", [])
    hr = result.get("hr_preparation", [])
    roadmap = result.get("roadmap", [])
    questions = result.get("interview_questions", [])

    lines = [
        "🎯 INTERVIEWLENS AI",
        "",
        "📊 JOB MATCH",
        f"Score: {score}/100",
        f"Level: {level}",
        "",
        "📝 MATCH ANALYSIS",
        explanation,
        "",
        "💪 STRENGTHS",
    ]

    if strengths:
        lines.extend([f"• {item}" for item in strengths])
    else:
        lines.append("• None identified")

    lines.extend([
        "",
        "⚠️ SKILL GAPS",
    ])

    if skill_gaps:
        lines.extend([f"• {item}" for item in skill_gaps])
    else:
        lines.append("• None identified")

    lines.extend([
        "",
        "🔑 MISSING KEYWORDS",
    ])

    if missing_keywords:
        lines.extend([f"• {item}" for item in missing_keywords])
    else:
        lines.append("• None identified")

    lines.extend([
        "",
        "🚀 PROJECT & EXPERIENCE ANALYSIS",
    ])

    if projects:
        for project in projects:
            lines.extend([
                f"• {project.get('project', 'Project')}",
                f"  Relevance: {project.get('relevance', '')}",
                f"  Improvement: {project.get('improvement', '')}",
            ])
    else:
        lines.append("• None available")

    lines.extend([
        "",
        "💻 TECHNICAL PREPARATION",
    ])

    if technical:
        lines.extend([f"• {item}" for item in technical])
    else:
        lines.append("• None available")

    lines.extend([
        "",
        "👔 HR PREPARATION",
    ])

    if hr:
        for item in hr:
            lines.extend([
                f"• {item.get('question', 'Interview Question')}",
                f"  Emphasize: {item.get('what_to_emphasize', '')}",
            ])
    else:
        lines.append("• None available")

    lines.extend([
        "",
        "📚 PERSONALIZED ROADMAP",
    ])

    if roadmap:
        for week in roadmap:
            lines.append(
                f"• {week.get('week', 'Week')} — {week.get('focus', '')}"
            )

            for task in week.get("tasks", []):
                lines.append(f"  - {task}")
    else:
        lines.append("• None available")

    lines.extend([
        "",
        "❓ TOP INTERVIEW QUESTIONS",
    ])

    if questions:
        for index, question in enumerate(questions, start=1):
            lines.append(f"{index}. {question}")
    else:
        lines.append("• None generated")

    lines.extend([
        "",
        "Generated by InterviewLens AI 🚀",
    ])

    return "\n".join(lines)


